// pllPredefinedByLocale finds a predefined language (REST create with only a locale).
func pllPredefinedByLocale(locale string) (pllPredefinedLang, bool) {
	for _, l := range pllPredefined {
		if l.Locale == locale {
			return l, true
		}
	}
	return pllPredefinedLang{}, false
}
