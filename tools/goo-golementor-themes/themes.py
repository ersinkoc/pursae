def review(author, rating, text):
    return {"author": author, "email": author.lower().split()[0] + "@example.com", "rating": rating, "content": text}


def p(slug, name, price, cats, desc, short, **kw):
    d = {"slug": slug, "name": name, "type": "simple", "regular_price": price, "categories": cats,
         "description": "".join(f"<p>{x}</p>" for x in desc), "short_description": f"<p>{short}</p>"}
    d.update(kw)
    return d


def variable(slug, name, attr, values, prices, cats, desc, short, sku, stock=12, sale_price=None, **kw):
    d = p(slug, name, prices[0], cats, desc, short, **kw)
    d["type"], d["sku"] = "variable", sku
    d["attributes"] = [{"name": attr, "values": values, "variation": True}]
    d["variations"] = [{"attributes": {attr: v}, "regular_price": prices[i], "stock": stock, "sku": f"{sku}-{i + 1}"}
                       for i, v in enumerate(values)]
    if sale_price:  # the first variation is on sale
        d["variations"][0]["sale_price"] = sale_price
    return d


